import "server-only";
import { prisma } from "./db";

/**
 * Backup portátil de UMA empresa (todos os registros de negócio em JSON).
 * Não inclui senhas, sessões nem bytes de fotos (os anexos são listados com seus metadados;
 * o backup do banco inteiro é feito por pg_dump — ver docs/BACKUP.md).
 */
export async function exportOrganization(orgId: string) {
  const where = { orgId };
  const [org, members, categories, locations, products, items, itemEvents, costEntries, contacts, purchases, purchaseLines, purchaseExtras, sales, saleLines, saleReturns, trades, tradeOut, tradeIn, tradeRevisions, builds, buildParts, buildExpenses, disassemblies, opportunities, accounts, financeCategories, titles, settlements, transactions, results, counts, countLines, imports, notes, attachments] = await Promise.all([
    prisma.organization.findUniqueOrThrow({ where: { id: orgId } }),
    prisma.membership.findMany({ where, include: { user: { select: { email: true, name: true } } } }),
    prisma.category.findMany({ where }),
    prisma.location.findMany({ where }),
    prisma.product.findMany({ where }),
    prisma.item.findMany({ where }),
    prisma.itemEvent.findMany({ where }),
    prisma.costEntry.findMany({ where }),
    prisma.contact.findMany({ where }),
    prisma.purchase.findMany({ where }),
    prisma.purchaseLine.findMany({ where }),
    prisma.purchaseExtra.findMany({ where }),
    prisma.sale.findMany({ where }),
    prisma.saleLine.findMany({ where }),
    prisma.saleReturn.findMany({ where }),
    prisma.trade.findMany({ where }),
    prisma.tradeOutLine.findMany({ where }),
    prisma.tradeInLine.findMany({ where }),
    prisma.tradeRevision.findMany({ where }),
    prisma.build.findMany({ where }),
    prisma.buildPart.findMany({ where }),
    prisma.buildExpense.findMany({ where }),
    prisma.disassembly.findMany({ where }),
    prisma.opportunity.findMany({ where }),
    prisma.moneyAccount.findMany({ where }),
    prisma.financeCategory.findMany({ where }),
    prisma.title.findMany({ where }),
    prisma.settlement.findMany({ where }),
    prisma.moneyTransaction.findMany({ where }),
    prisma.resultEntry.findMany({ where }),
    prisma.stockCount.findMany({ where }),
    prisma.stockCountLine.findMany({ where }),
    prisma.importBatch.findMany({ where }),
    prisma.note.findMany({ where }),
    prisma.attachment.findMany({ where, select: { id: true, entityType: true, entityId: true, kind: true, fileName: true, contentType: true, sizeBytes: true, createdAt: true } }),
  ]);
  return {
    format: "aionix-gear-backup",
    version: 1,
    exportedAt: new Date().toISOString(),
    note: "Valores monetários em centavos (inteiros). Datas em UTC (ISO 8601).",
    organization: org,
    members: members.map((m) => ({ role: m.role, email: m.user.email, name: m.user.name })),
    categories,
    locations,
    products,
    items,
    itemEvents,
    costEntries,
    contacts,
    purchases,
    purchaseLines,
    purchaseExtras,
    sales,
    saleLines,
    saleReturns,
    trades,
    tradeOutLines: tradeOut,
    tradeInLines: tradeIn,
    tradeRevisions,
    builds,
    buildParts,
    buildExpenses,
    disassemblies,
    opportunities,
    moneyAccounts: accounts,
    financeCategories,
    titles,
    settlements,
    moneyTransactions: transactions,
    resultEntries: results,
    stockCounts: counts,
    stockCountLines: countLines,
    importBatches: imports,
    notes,
    attachments,
  };
}
